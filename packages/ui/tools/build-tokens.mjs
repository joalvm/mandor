import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
    amber,
    amberDark,
    blue,
    blueDark,
    grass,
    grassDark,
    gray,
    grayA,
    grayDark,
    grayDarkA,
    iris,
    irisDark,
    pink,
    pinkDark,
    red,
    redDark,
} from '@radix-ui/colors';

import { BRAND_RAMPS } from './brand-ramps.mjs';
import { MARKDOWN_PALETTE } from './markdown-palette.mjs';
import { createTokenModuleSources } from './token-module-source.mjs';

const PACKAGE_DIR = join(dirname(fileURLToPath(import.meta.url)), '..');
const STYLES_DIR = join(PACKAGE_DIR, 'src', 'styles');
const STEPS = Array.from({ length: 12 }, (_, index) => String(index + 1));
/**
 * The head of the neutral ramp is the chrome of the window, and its steps are chosen and not
 * derived: white for the body, one step for the panels that frame it, and three more for the
 * states a tab and a title bar control pass through. The rest of the ramp stays as it comes,
 * so text and the borders that survive keep a scale that was built to stay legible. The frame
 * the cards rest on takes step 2, a point deeper than the ramp's own, so a white card reads as
 * raised above it without a line around it.
 */
const CHROME = {
    gray1: '#ffffff',
    gray2: '#f4f4f4',
    gray3: '#f2f2f2',
    gray4: '#ededed',
    gray5: '#e6e6e6',
};
const RAMP_SOURCES = {
    neutral: [{ ...gray, ...CHROME }, grayDark, 'gray'],
    green: [grass, grassDark, 'grass'],
    // Status text is read on the frame as well as on a card, and the frame is a step deeper than
    // white: step 11 of amber and of blue darkens along its hue to the first value that keeps
    // 4.5:1 on both.
    amber: [{ ...amber, amber11: '#976500' }, amberDark, 'amber'],
    red: [red, redDark, 'red'],
    blue: [{ ...blue, blue11: '#0d70c8' }, blueDark, 'blue'],
    iris: [iris, irisDark, 'iris'],
    pink: [pink, pinkDark, 'pink'],
};

function valuesOf(source, prefix) {
    return Array.from({ length: 12 }, (_, index) => source[`${prefix}${String(index + 1)}`]);
}

function declarationsFor(name, mode, values) {
    return values.map(
        (value, index) => `    --primitive-${name}-${mode}-${String(index + 1)}: ${value};`,
    );
}

/** Points every step of the accent at one brand ramp, in both modes. */
function accentBlock(selector, ramp) {
    const lines = ['light', 'dark'].flatMap((mode) =>
        STEPS.map(
            (step) =>
                `    --primitive-accent-${mode}-${step}: var(--primitive-${ramp}-${mode}-${step});`,
        ),
    );

    return [`${selector} {`, ...lines, '}', ''];
}

/**
 * The semantic layer names the accent and never a ramp. The first brand ramp is the accent of a
 * window that names none, or one this list does not know; the root of a window picks any other.
 */
function accentBlocks() {
    const [fallback, ...others] = Object.keys(BRAND_RAMPS);

    return [
        '/* The accent of the window: the root names its ramp, and the first one is the default. */',
        ...accentBlock(':root', fallback),
        ...others.flatMap((ramp) => accentBlock(`:root[data-accent='${ramp}']`, ramp)),
    ];
}

function createPrimitives() {
    const lines = ['/* Generated by tools/build-tokens.mjs. Do not edit. */', ':root {'];

    for (const [name, [light, dark, prefix]] of Object.entries(RAMP_SOURCES)) {
        lines.push(...declarationsFor(name, 'light', valuesOf(light, prefix)));
        lines.push(...declarationsFor(name, 'dark', valuesOf(dark, prefix)));
    }

    for (const [name, [light, dark]] of Object.entries(BRAND_RAMPS)) {
        lines.push(...declarationsFor(name, 'light', light));
        lines.push(...declarationsFor(name, 'dark', dark));
    }

    // The blue a resolved variable carries: the Postman family the interface inherited for
    // it, one readable step per mode. A whole ramp was never built for it and is not needed.
    lines.push('    --primitive-variable-light-11: #2552aa;');
    lines.push('    --primitive-variable-dark-11: #8ab4ff;');
    // The red of the one verb that destroys rests on step 11 of the red ramp, the first that
    // carries a white label legibly; steps 9 and 10 do not. The pointer and the press darken it
    // along the same hue, and a ramp has no step past 11 that is still that red.
    lines.push('    --primitive-danger-hover: #b9282c;');
    lines.push('    --primitive-danger-active: #a52327;');
    // The blue of a divider under the pointer: the one hue nothing else in the window wears, so
    // the line reads as the thing that moves in either scheme, whatever the accent of the app.
    lines.push('    --primitive-handle: #00a4f4;');

    // The page of a doc is GitHub's, and so are its colours.
    for (const [mode, colours] of Object.entries(MARKDOWN_PALETTE)) {
        for (const [name, value] of Object.entries(colours)) {
            lines.push(`    --primitive-markdown-${mode}-${name}: ${value};`);
        }
    }

    lines.push(
        ...valuesOf(grayA, 'grayA').map(
            (value, index) => `    --primitive-neutral-a-${String(index + 1)}: ${value};`,
        ),
    );
    // The dark scheme lifts what a light one deepens: its translucent steps are of white.
    lines.push(
        ...valuesOf(grayDarkA, 'grayA').map(
            (value, index) => `    --primitive-neutral-dark-a-${String(index + 1)}: ${value};`,
        ),
    );
    lines.push('}', '', ...accentBlocks());

    return lines.join('\n');
}

async function main() {
    const primitives = createPrimitives();
    const modules = await createTokenModuleSources(
        STYLES_DIR,
        primitives,
        Object.keys(BRAND_RAMPS),
    );
    const outputs = new Map([
        [join(STYLES_DIR, 'primitives.css'), primitives],
        [join(STYLES_DIR, 'token-color-values.ts'), modules.colors],
        [join(STYLES_DIR, 'token-contrast-values.ts'), modules.contrast],
        [join(STYLES_DIR, 'token-accent-values.ts'), modules.accents],
        [join(STYLES_DIR, 'token-scale-values.ts'), modules.scales],
        [join(STYLES_DIR, 'token-values.ts'), modules.tokens],
    ]);
    const check = process.argv.includes('--check');

    for (const [path, expected] of outputs) {
        const actual = await readFile(path, 'utf8').catch(() => null);

        if (check && actual !== expected) {
            console.error(`${path} is out of date`);
            process.exitCode = 1;
        }

        if (!check) {
            await writeFile(path, expected, 'utf8');
        }
    }
}

await main();
